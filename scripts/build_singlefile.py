def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build Orca AI Assistant single-file bundle.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify that the existing output file matches the generated bundle byte-for-byte.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Target output file path (defaults to <repo_root>/orca_ai_assistant_any.py).",
    )
    args = parser.parse_args(argv)

    repo_root = Path(__file__).resolve().parent.parent
    out_path = (args.output or (repo_root / "orca_ai_assistant_any.py")).resolve()

    bundle_source = build_bundle_source(repo_root)

    if args.check:
        if not out_path.is_file():
            print(f"[FAIL] Bundle file does not exist: {out_path}", file=sys.stderr)
            return 1
        existing = _normalize_newlines(out_path.read_text(encoding="utf-8"))
        if existing != bundle_source:
            print(
                f"[FAIL] {out_path.name} is out of date with src/orca_ai_assistant/. "
                "Run `python scripts/build_singlefile.py` to rebuild.",
                file=sys.stderr,
            )
            return 1
        print(f"[OK] {out_path.name} is up to date ({len(bundle_source.encode('utf-8'))} bytes).")
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(bundle_source)

    print(
        f"[OK] Built {out_path.name} ({len(bundle_source.encode('utf-8'))} bytes) "
        f"from {repo_root / 'src' / 'orca_ai_assistant'}."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
