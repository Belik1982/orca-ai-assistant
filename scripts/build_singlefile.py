class _BundledPackageImporter(importlib.abc.MetaPathFinder, importlib.abc.InspectLoader):
    """In-memory virtual package loader preserving exact module names and stack traces."""

    _BUNDLE_FILE: str = __file__
    _BUNDLE_DIR: Path = Path(__file__).resolve().parent

    def find_spec(
        self,
        fullname: str,
        path: Any = None,
        target: Any = None,
    ) -> importlib.machinery.ModuleSpec | None:
        if fullname == "orca_ai_assistant._bundled_assets":
            pkg = sys.modules.get("orca_ai_assistant")
            if pkg is None or getattr(pkg, "__loader__", None) is self:
                return importlib.machinery.ModuleSpec(fullname, self, is_package=False)
            return None

        entry = _BUNDLED_MODULES.get(fullname)
        if entry is None:
            return None

        _source, is_pkg = entry
        spec = importlib.machinery.ModuleSpec(
            fullname,
            self,
            origin=self.get_filename(fullname),
            is_package=is_pkg,
        )
        if is_pkg:
            spec.submodule_search_locations = [str(self._BUNDLE_DIR / fullname.replace(".", "/"))]
        return spec

    def is_package(self, fullname: str) -> bool:
        if fullname == "orca_ai_assistant._bundled_assets":
            return False
        entry = _BUNDLED_MODULES.get(fullname)
        if entry is None:
            raise ImportError(fullname)
        return entry[1]

    def get_filename(self, fullname: str) -> str:
        rel = fullname.replace(".", "/")
        if fullname != "orca_ai_assistant._bundled_assets":
            entry = _BUNDLED_MODULES.get(fullname)
            if entry is not None and entry[1]:
                return str(self._BUNDLE_DIR / rel / "__init__.py")
        return str(self._BUNDLE_DIR / f"{{rel}}.py")

    def get_source(self, fullname: str) -> str:
        if fullname == "orca_ai_assistant._bundled_assets":
            return ""
        entry = _BUNDLED_MODULES.get(fullname)
        if entry is None:
            raise ImportError(fullname)
        return entry[0]

    def create_module(self, spec: importlib.machinery.ModuleSpec) -> Any:
        return None

    def exec_module(self, module: Any) -> None:
        fullname = module.__name__
        if fullname == "orca_ai_assistant._bundled_assets":
            module.ASSETS = _BUNDLED_ASSETS
            module.BUNDLE_FILE = self._BUNDLE_FILE
            return

        source = self.get_source(fullname)
        filename = self.get_filename(fullname)
        module.__file__ = filename
        code = compile(source, filename, "exec")
        exec(code, module.__dict__)
        if fullname == "orca_ai_assistant":
            module._BUNDLED_ASSETS = _BUNDLED_ASSETS
            module._BUNDLE_FILE = self._BUNDLE_FILE


