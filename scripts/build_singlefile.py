"""Deterministic single-file bundler for Orca AI Assistant.

Bundles all Python modules under ``src/orca_ai_assistant/`` and all static text
assets under ``assets/`` and ``ui/`` into a single self-contained
``orca_ai_assistant_any.py`` script with a PEP 723 metadata header suitable for
direct installation in OrcaSlicer 2.5+ and publication to OrcaCloud.

Usage:
    python scripts/build_singlefile.py
    python scripts/build_singlefile.py --check
    python scripts/build_singlefile.py --output path/to/out.py
"""

